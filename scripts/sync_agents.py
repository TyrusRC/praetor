#!/usr/bin/env python3
"""Generate native per-agent wrapper files for every supported agent harness.

Single source of truth: `.claude/agents/*.md` (the full role manuals). Each other
harness that supports per-agent subagents gets a THIN wrapper — native frontmatter
plus a short body that points back to `.claude/agents/<role>.md`. The detail lives
in one place, so a second copy cannot drift (the failure this replaces: `.gemini/`
shipped 3 of 19 roles).

Add a harness: write one `emit_<harness>(agent) -> (relpath, content)` function and
register it in HARNESSES. Windsurf / Cursor / dsh use a single always-on operating
guide instead of a per-agent roster, so they are not generated here.

Usage:
  uv run python scripts/sync_agents.py            # write all harnesses
  uv run python scripts/sync_agents.py --harness opencode
  uv run python scripts/sync_agents.py --check    # CI: exit 1 if any file is stale
  uv run python scripts/sync_agents.py --list     # list supported harnesses
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

GENERATED_MARK = "GENERATED by scripts/sync_agents.py"

# Claude model pin -> host-agnostic tier (mirrors AGENTS.md / list_agents()).
_TIER = {"opus": "strategic", "sonnet": "standard", "haiku": "fast"}


def tier_for(model: str | None) -> str:
    """Map a Claude model pin to a host-agnostic tier. Unpinned -> standard."""
    return _TIER.get((model or "").strip(), "standard")


def _frontmatter(text: str) -> dict:
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    fm: dict[str, str] = {}
    if not m:
        return fm
    for key in ("name", "description", "model"):
        km = re.search(rf"^{key}:\s*(.+)$", m.group(1), re.M)
        if km:
            fm[key] = km.group(1).strip()
    return fm


def load_canonical(root: Path) -> list[dict]:
    """Parse every `.claude/agents/*.md` into {name, description, model}."""
    agents = []
    for path in sorted((root / ".claude" / "agents").glob("*.md")):
        fm = _frontmatter(path.read_text(encoding="utf-8"))
        name = fm.get("name") or path.stem
        agents.append({
            "name": name,
            "description": fm.get("description", ""),
            "model": fm.get("model"),
        })
    return agents


def emit_opencode(agent: dict) -> tuple[str, str]:
    name = agent["name"]
    tier = tier_for(agent.get("model"))
    content = f"""---
description: {agent['description']}
mode: subagent
---

You are **{name}** for the Praetor pentest harness, running as an opencode subagent.

Operate through the Praetor MCP tools. Your operating manual is
`.claude/agents/{name}.md` — read it in full before acting (it lists the exact tools
and the return contract). Always-in-force rules: `.claude/rules/`. Load task
playbooks with `get_skill("<name>")` (or `list_skills()` to browse).

Tier: {tier}. opencode is often single-model — map this tier to your configured
model; a single-model host runs every role on that model. HARD rules always apply:
`check_scope(url)` before any new domain; no destructive payloads; never exfiltrate
or modify real user data. Full roster + dispatch contract: `AGENTS.md`.

<!-- {GENERATED_MARK} from .claude/agents/{name}.md — do not edit by hand. -->
"""
    return f".opencode/agent/{name}.md", content


def emit_gemini(agent: dict) -> tuple[str, str]:
    name = agent["name"]
    tier = tier_for(agent.get("model"))
    content = f"""---
name: {name}
description: {agent['description']}
---

You are **{name}** for the Praetor harness, running as a Gemini CLI subagent.
Operate through the Praetor MCP tools. Your operating manual is
`.claude/agents/{name}.md` — read it before acting. Load playbooks with
`get_skill("<name>")`; rules are in `.claude/rules/`. HARD rules always apply
(see `GEMINI.md`).

Tier: {tier}.

<!-- {GENERATED_MARK} from .claude/agents/{name}.md — do not edit by hand. -->
"""
    return f".gemini/agents/{name}.md", content


HARNESSES = {
    "opencode": emit_opencode,
    "gemini": emit_gemini,
}


def generate(agents: list[dict], harnesses: list[str]) -> dict[str, str]:
    """Return {repo_relative_path: content} for the requested harnesses."""
    out: dict[str, str] = {}
    for harness in harnesses:
        emit = HARNESSES[harness]
        for agent in agents:
            path, content = emit(agent)
            out[path] = content
    return out


def sync(root: Path, harnesses: list[str], check: bool = False,
         agents: list[dict] | None = None) -> list[tuple[str, str]]:
    """Write (or, with check=True, compare) every wrapper. Returns (path, status).

    status is 'written' | 'ok' | 'stale' | 'missing'. check never writes.
    """
    if agents is None:
        agents = load_canonical(root)
    files = generate(agents, harnesses)
    results: list[tuple[str, str]] = []
    for rel, content in sorted(files.items()):
        dest = root / rel
        if check:
            if not dest.exists():
                results.append((rel, "missing"))
            elif dest.read_text(encoding="utf-8") != content:
                results.append((rel, "stale"))
            else:
                results.append((rel, "ok"))
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            if dest.exists() and dest.read_text(encoding="utf-8") == content:
                results.append((rel, "ok"))
            else:
                dest.write_text(content, encoding="utf-8")
                results.append((rel, "written"))
    return results


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--harness", action="append", choices=sorted(HARNESSES),
                    help="limit to one harness (repeatable); default: all")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any wrapper is missing or stale (CI gate)")
    ap.add_argument("--list", action="store_true",
                    help="list supported harnesses and exit")
    args = ap.parse_args(argv)

    if args.list:
        for h in sorted(HARNESSES):
            print(h)
        return 0

    root = Path(__file__).resolve().parents[1]
    harnesses = args.harness or sorted(HARNESSES)
    results = sync(root, harnesses, check=args.check)

    bad = [(p, s) for p, s in results if s in ("stale", "missing")]
    if args.check:
        if bad:
            print("DRIFT — run: uv run python scripts/sync_agents.py", file=sys.stderr)
            for p, s in bad:
                print(f"  {s:8} {p}", file=sys.stderr)
            return 1
        print(f"check OK — {len(results)} wrappers across {len(harnesses)} harness(es)")
        return 0

    written = sum(1 for _, s in results if s == "written")
    print(f"synced {len(results)} wrappers across {len(harnesses)} harness(es) "
          f"({written} changed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
